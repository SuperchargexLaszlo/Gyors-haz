// ──────────────────────────────────────────────────────────────
// Google Sheets CSV fetch (build-time) — merge mode
// Sheet columns: id | ar_eur | ar_ft | ar_kulcsrakesz_ft | ar_deviza | aktiv
// ──────────────────────────────────────────────────────────────

const SHEETS_CSV_URL = import.meta.env['SHEETS_CSV_URL'] as string | undefined;

async function fetchPriceOverrides(): Promise<Map<string, Partial<Product>> | null> {
  if (!SHEETS_CSV_URL) return null;

  try {
    const res = await fetch(SHEETS_CSV_URL);
    if (!res.ok) return null;
    const text = await res.text();

    const lines = text.trim().split('\n');
    if (lines.length < 2) return null;

    const headers = lines[0]!.split(',').map((h) => h.trim().replace(/^"|"$/g, ''));

    const overrides = new Map<string, Partial<Product>>();
    for (let i = 1; i < lines.length; i++) {
      const line = lines[i];
      if (!line?.trim()) continue;
      const cols = line.split(',').map((c) => c.trim().replace(/^"|"$/g, ''));

      const row: Record<string, string> = {};
      headers.forEach((h, idx) => {
        row[h] = cols[idx] ?? '';
      });

      const id = row['id']?.trim();
      if (!id) continue;

      const override: Partial<Product> = {};
      if (Number(row['ar_eur']) > 0) override.ar_eur = Number(row['ar_eur']);
      if (Number(row['ar_ft']) > 0) override.ar_ft = Number(row['ar_ft']);
      if (row['ar_kulcsrakesz_ft']) override.ar_kulcsrakesz_ft = Number(row['ar_kulcsrakesz_ft']) || undefined;
      if (row['ar_deviza']) override.ar_deviza = row['ar_deviza'].trim() as 'EUR' | 'HUF';
      if (row['aktiv']) override.aktiv = row['aktiv'].trim().toLowerCase() === 'igen';

      overrides.set(id, override);
    }

    return overrides.size > 0 ? overrides : null;
  } catch (e) {
    console.warn('Sheets fetch failed, using fallback:', e);
    return null;
  }
}

let _cache: Product[] | null = null;

async function loadProducts(): Promise<Product[]> {
  if (_cache) return _cache;

  const overrides = await fetchPriceOverrides();
  if (!overrides) {
    _cache = FALLBACK_PRODUCTS;
    return _cache;
  }

  // Merge: statikus termékadatok + Sheets árfelülírások
  _cache = FALLBACK_PRODUCTS.map((product) => {
    const override = overrides.get(product.id);
    if (!override) return product;
    return { ...product, ...override };
  });

  return _cache;
}

// ──────────────────────────────────────────────────────────────
// Public API
// ──────────────────────────────────────────────────────────────

export async function getProducts(): Promise<Product[]> {
  const all = await loadProducts();
  return all.filter((p) => p.aktiv);
}

export async function getProductsByKategoria(
  kat: Product['kategoria'],
): Promise<Product[]> {
  const all = await getProducts();
  return all.filter((p) => p.kategoria === kat);
}

export async function getProductBySlug(slug: string): Promise<Product | undefined> {
  const all = await getProducts();
  return all.find((p) => p.slug === slug);
}

export function formatAr(product: Product): string {
  if (product.ar_deviza === 'HUF' && product.ar_ft) {
    const szam = product.ar_ft.toLocaleString('hu-HU').replace(/\s/g, '\u00a0');
    return product.afa ? `${szam} Ft + ÁFA` : `${szam} Ft`;
  }
  if (!product.ar_eur || product.ar_eur === 0) return 'Ár: érdeklődjön!';
  const formatted = product.ar_eur.toLocaleString('hu-HU').replace(/\s/g, '.');
  const tol = product.valtozatok?.length ? '-tól' : '';
  return product.afa ? `${formatted} EUR + ÁFA${tol}` : `${formatted} EUR${tol}`;
}

export function negyzetmeterAr(product: Product): string {
  if (product.ar_deviza === 'HUF' && product.ar_ft) {
    const ertek = Math.round(product.ar_ft / product.meret_m2);
    return `${ertek.toLocaleString('hu-HU').replace(/\s/g, '.')} Ft/m²`;
  }
  if (!product.meret_m2 || !product.ar_eur) return '';
  const perM2 = Math.round(product.ar_eur / product.meret_m2);
  return `${perM2.toLocaleString('hu-HU').replace(/\s/g, '.')} EUR/m²`;
}

export function formatKulcsrakeszAr(product: Product): string {
  if (!product.ar_kulcsrakesz_ft) return '';
  const szam = product.ar_kulcsrakesz_ft.toLocaleString('hu-HU').replace(/\s/g, '\u00a0');
  return product.afa ? `${szam} Ft + ÁFA` : `${szam} Ft`;
}

export function formatEur(ertek: number, afa = true): string {
  const formatted = ertek.toLocaleString('hu-HU').replace(/\s/g, '.');
  return afa ? `${formatted} EUR + ÁFA` : `${formatted} EUR`;
}

export function formatM2(m2: number): string {
  return String(m2).replace('.', ',');
}
